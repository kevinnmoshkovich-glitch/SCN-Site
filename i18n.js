window.LANG = (function () {
  try { const s = localStorage.getItem('fc_lang'); if (s === 'es' || s === 'en') return s; } catch (e) { /* private mode */ }
  return (navigator.language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
})();

window.t = (key) => (window.I18N[window.LANG] && window.I18N[window.LANG][key]) || window.I18N.en[key] || key;

window.applyLang = function (lang) {
  window.LANG = lang;
  try { localStorage.setItem('fc_lang', lang); } catch (e) { /* private mode */ }
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = window.t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = window.t(el.dataset.i18nPh); });
  document.querySelectorAll('.lang button').forEach((b) => b.classList.toggle('on', b.dataset.lang === lang));
  document.dispatchEvent(new CustomEvent('langchange'));
};

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang button').forEach((b) =>
    b.addEventListener('click', () => window.applyLang(b.dataset.lang)));
  window.applyLang(window.LANG);
});
